#!/usr/bin/env bash
# proto-gen-ext.sh — Generate protobuf types for all supported languages.
#
# Usage:
#   ./scripts/proto-gen-ext.sh <language>   # e.g. python, rust, ts, all
#   ./scripts/proto-gen-ext.sh --python     # legacy flag style also works
#   ./scripts/proto-gen-ext.sh --module <source> <language>
#   ./scripts/proto-gen-ext.sh --help
#
# Every source in scripts/proto-sources.conf is exported without imports and
# unioned into one proto tree. Each language is generated once from a single
# descriptor image of that tree, staged, and only then copied over the
# codegen-owned output.
#
# Post-processors are auto-discovered from scripts/post/<lang>.{sh,py}.

set -eo pipefail

ROOT_DIR="$(cd "$(dirname "$(dirname "$0")")" && pwd)"
BUF_DIR="$ROOT_DIR/buf"
POST_DIR="$ROOT_DIR/scripts/post"
SOURCES_CONF="$ROOT_DIR/scripts/proto-sources.conf"

# Make locally-installed buf plugins (ts-proto, etc.) available without global install
export PATH="$ROOT_DIR/ts/node_modules/.bin:$PATH"

# Replaces the source that owns the `xion` root (Git URL or BSR reference).
XION_OVERRIDE="${XION_BSR_MODULE:-}"

ALL_LANGUAGES="c cpp csharp docs java kotlin objc php python ruby rust scala swift ts"

# Leaked test/internal packages removed from generated output.
EXCLUDE_PACKAGES="test_proto proto3_proto com capability"

TS_CODEGEN_HEADER="// Code generated by protoc-gen-ts_proto. DO NOT EDIT."

WORK_DIR=""
IMAGE=""

die() {
  echo "Error: $*" >&2
  exit 1
}

cleanup() {
  if [ -n "$WORK_DIR" ]; then rm -rf "$WORK_DIR"; fi
}
trap cleanup EXIT

# ─── Sources ─────────────────────────────────────────────────────────

load_sources() {
  SRC_KINDS=()
  SRC_URLS=()
  SRC_ROOTS=()
  local line kind src roots
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line#"${line%%[![:space:]]*}"}"
    case "$line" in ''|'#'*) continue ;; esac
    read -r kind src roots <<<"$line"
    case "$kind" in
      target|import) ;;
      *) die "proto-sources.conf: unknown kind '$kind' in: $line" ;;
    esac
    [ -n "$roots" ] || die "proto-sources.conf: no owned roots for $src"
    if [ -n "$XION_OVERRIDE" ] && [[ " $roots " == *" xion "* ]]; then
      src="$XION_OVERRIDE"
    fi
    SRC_KINDS+=("$kind")
    SRC_URLS+=("$src")
    SRC_ROOTS+=("$roots")
  done < "$SOURCES_CONF"
  [ "${#SRC_URLS[@]}" -gt 0 ] || die "proto-sources.conf lists no sources"
}

# Length of the longest root of source $1 that contains path $2 (0 if none).
root_match_len() {
  local best=0 root
  for root in ${SRC_ROOTS[$1]}; do
    if [ "$2" = "$root" ] || [[ "$2" == "$root"/* ]]; then
      if [ "${#root}" -gt "$best" ]; then best="${#root}"; fi
    fi
  done
  echo "$best"
}

# Export every source and union the files each source owns into $WORK_DIR/src.
prepare_tree() {
  [ -z "$IMAGE" ] || return 0
  WORK_DIR="$(mktemp -d)"
  local union="$WORK_DIR/src" origins="$WORK_DIR/origins" targets="$WORK_DIR/targets"
  mkdir -p "$union"
  : > "$origins"
  : > "$targets"

  local i j rel stage mine len best prev
  for i in "${!SRC_URLS[@]}"; do
    stage="$WORK_DIR/export/$i"
    echo "  exporting ${SRC_URLS[$i]}"
    buf export "${SRC_URLS[$i]}" --exclude-imports --output "$stage" \
      || die "buf export failed for ${SRC_URLS[$i]}"

    while IFS= read -r rel; do
      mine="$(root_match_len "$i" "$rel")"
      best=0
      for j in "${!SRC_URLS[@]}"; do
        len="$(root_match_len "$j" "$rel")"
        if [ "$len" -gt "$best" ]; then best="$len"; fi
      done
      [ "$best" -gt 0 ] || die "$rel from ${SRC_URLS[$i]} has no owner in proto-sources.conf"
      if [ "$mine" -lt "$best" ]; then
        echo "    skipping $rel (not owned by this source)"
        continue
      fi

      if [ -e "$union/$rel" ]; then
        if ! cmp -s "$stage/$rel" "$union/$rel"; then
          prev="$(awk -F '\t' -v p="$rel" '$1 == p { print $2; exit }' "$origins")"
          die "conflicting definitions of $rel from $prev and ${SRC_URLS[$i]}"
        fi
        continue
      fi
      mkdir -p "$(dirname "$union/$rel")"
      cp "$stage/$rel" "$union/$rel"
      printf '%s\t%s\n' "$rel" "${SRC_URLS[$i]}" >> "$origins"
      if [ "${SRC_KINDS[$i]}" = "target" ]; then echo "$rel" >> "$targets"; fi
    done < <(cd "$stage" && find . -type f -name '*.proto' | sed 's|^\./||' | LC_ALL=C sort)
  done

  [ -s "$targets" ] || die "no target proto files found"
  printf 'version: v2\n' > "$union/buf.yaml"

  local path_args=()
  while IFS= read -r rel; do path_args+=(--path "$rel"); done < "$targets"
  IMAGE="$WORK_DIR/image.binpb"
  echo "  building descriptor image ($(wc -l < "$targets" | tr -d ' ') target files)"
  (cd "$union" && buf build . "${path_args[@]}" --output "$IMAGE") \
    || die "buf build failed for the unioned proto tree"
}

# ─── Output ──────────────────────────────────────────────────────────

template_out_dirs() {
  local out
  for out in $(grep -E '^[[:space:]]*out:' "$1" | sed -E 's/^[[:space:]]*out:[[:space:]]*//' | sort -u); do
    case "$out" in
      .|/*|*..*) die "$(basename "$1"): output dir '$out' must be a subdirectory of the repo" ;;
    esac
    echo "$out"
  done
}

# Replace the codegen-owned files of $1's output dirs with the staged ones in $2.
replace_outputs() {
  local template="$1" stage="$2" outs out pkg
  outs="$(template_out_dirs "$template")"
  for out in $outs; do
    [ -d "$stage/$out" ] || die "generation produced no output for $out"
    for pkg in $EXCLUDE_PACKAGES; do
      # Java classes import com.google.api and com.google.protobuf.GoGoProtos from here.
      if [ "$out" = "java/types" ] && [ "$pkg" = "com" ]; then continue; fi
      if [ -d "$stage/$out/$pkg" ]; then
        echo "  removing excluded package: $out/$pkg"
        rm -rf "${stage:?}/$out/$pkg"
      fi
    done
  done
  for out in $outs; do
    if [ "$out" = "ts/types" ]; then
      # ts/types also holds hand-maintained helpers; only ts-proto files are codegen-owned.
      if [ -d "$ROOT_DIR/$out" ]; then
        while IFS= read -r f; do
          if [ "$(head -n 1 "$f")" = "$TS_CODEGEN_HEADER" ]; then rm -f "$f"; fi
        done < <(find "$ROOT_DIR/$out" -type f -name '*.ts')
      fi
    else
      rm -rf "${ROOT_DIR:?}/$out"
    fi
    mkdir -p "$ROOT_DIR/$out"
    cp -R "$stage/$out/." "$ROOT_DIR/$out/"
  done
}

# ─── Core generation ─────────────────────────────────────────────────

run_buf_generate() {
  local template="$1" stage="$2"
  shift 2
  # Run from the root so plugin options with relative paths (docs template) resolve.
  (cd "$ROOT_DIR" && buf generate "$IMAGE" --template "$template" --output "$stage" "$@") \
    || die "buf generate failed for $(basename "$template")"
}

# protoc's PHP generator rejects proto2, so PHP targets only proto3 files
# while the image still carries the imported proto2 definitions.
write_php_paths() {
  buf build "$IMAGE" --output "$WORK_DIR/image.json" || die "buf build failed converting image to JSON"
  jq -r '.file[] | select(.syntax == "proto3") | .name | select(startswith("google/protobuf/") | not)' \
    "$WORK_DIR/image.json" > "$1" || die "jq failed listing proto3 files"
  [ -s "$1" ] || die "no proto3 files found for php"
}

gen_language() {
  local language="$1"
  local template="$BUF_DIR/buf.gen.$language.yaml"
  [ -f "$template" ] || die "no buf template at $template"

  prepare_tree
  local stage="$WORK_DIR/out/$language"
  rm -rf "$stage"
  mkdir -p "$stage"

  case "$language" in
    php)
      local path_args=() rel
      write_php_paths "$WORK_DIR/php-paths"
      while IFS= read -r rel; do path_args+=(--path "$rel"); done < "$WORK_DIR/php-paths"
      run_buf_generate "$template" "$stage" "${path_args[@]}"
      ;;
    kotlin)
      # Kotlin wrappers compile against the Java classes from the same image.
      run_buf_generate "$template" "$stage" --include-imports
      run_buf_generate "$BUF_DIR/buf.gen.java.yaml" "$stage" --include-imports
      replace_outputs "$BUF_DIR/buf.gen.java.yaml" "$stage"
      ;;
    *)
      run_buf_generate "$template" "$stage" --include-imports
      ;;
  esac

  replace_outputs "$template" "$stage"
}

# ─── Post-processing (auto-discovered from scripts/post/) ───────────

run_post() {
  local language="$1"
  cd "$ROOT_DIR"

  if [ -f "$POST_DIR/$language.sh" ]; then
    echo "Running post-processor: scripts/post/$language.sh"
    bash "$POST_DIR/$language.sh"
  elif [ -f "$POST_DIR/$language.py" ]; then
    echo "Running post-processor: scripts/post/$language.py"
    python3 "$POST_DIR/$language.py"
  fi
}

# ─── Generate one language ───────────────────────────────────────────

generate_one() {
  local language="$1"
  echo ""
  echo "━━━ $language ━━━"
  gen_language "$language"
  run_post "$language"
  echo "✅ $language done"
}

generate_all() {
  for lang in $ALL_LANGUAGES; do
    generate_one "$lang"
  done
  echo ""
  echo "✅ All languages generated"
}

# ─── CLI ─────────────────────────────────────────────────────────────

show_help() {
  echo "Usage: $(basename "$0") [--module <source>] <language|all>"
  echo ""
  echo "Generate protocol buffer types for Xion blockchain."
  echo ""
  echo "Proto sources:"
  local i
  for i in "${!SRC_URLS[@]}"; do echo "  ${SRC_KINDS[$i]} ${SRC_URLS[$i]} (${SRC_ROOTS[$i]})"; done
  echo ""
  echo "Languages: $ALL_LANGUAGES"
  echo "  all     Generate all of the above"
  echo ""
  echo "Options:"
  echo "  --module <source>  Replace the pinned xion source (Git URL or BSR reference)"
  echo "                     e.g. buf.build/burnt-labs/xion:v26.0.0"
  echo ""
  echo "Both bare names and --flags work: 'python' or '--python'"
}

main() {
  if [ "$1" = "--module" ]; then
    [ -n "$2" ] || die "--module requires a source"
    XION_OVERRIDE="$2"
    shift 2
  fi
  load_sources

  if [ $# -eq 0 ] || [ "$1" = "-h" ] || [ "$1" = "--help" ]; then
    show_help
    exit 0
  fi

  while [ $# -gt 0 ]; do
    # Strip leading -- for backwards compat (--python → python)
    local target="${1#--}"
    shift

    if [ "$target" = "all" ]; then
      generate_all
    elif echo " $ALL_LANGUAGES " | grep -q " $target "; then
      generate_one "$target"
    else
      echo "Unknown language: $target"
      echo "Valid: $ALL_LANGUAGES all"
      exit 1
    fi
  done
}

main "$@"
